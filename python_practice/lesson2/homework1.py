"""
Взагалі у театральному гуртку - 24 хлопчики, а дівчаток - вдвічі менше.
1 хлопчик захворів та 2 дівчинки не прийшли сьогодні.
Скількі сьогодні дітей у театральному гуртку?
"""
# Скільки дітей у гуртку взагалі
хлопчики_всього = 24
дівчатка_всього = хлопчики_всього // 2  # вдвічі менше

# Хто прийшов сьогодні
хлопчики_сьогодні = хлопчики_всього - 1
дівчатка_сьогодні = дівчатка_всього - 2

# Рахуємо всіх, хто прийшов
дітей_сьогодні = хлопчики_сьогодні + дівчатка_сьогодні

# Вивід результату
print(f"Сьогодні прийшло хлопчиків: {хлопчики_сьогодні}")
print(f"Сьогодні прийшло дівчаток: {дівчатка_сьогодні}")
print(f"Всього сьогодні на гуртку {дітей_сьогодні} дітей!")

